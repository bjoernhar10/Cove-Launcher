def played(
    game_id: str,
    title: str,
    hours: float,
    *,
    days_ago: float = 1,
    favorite: bool = False,
    sessions: int = 10,
    achievements: tuple[int, int] = (0, 0),
) -> LibraryGame:
    return LibraryGame(
        game_id=game_id,
        title=title,
        playtime_minutes=round(hours * 60),
        last_played_at=NOW - timedelta(days=days_ago) if hours > 0 else None,
        favorite=favorite,
        achievements_unlocked=achievements[0],
        achievements_total=achievements[1],
        session_count=sessions,
    )
